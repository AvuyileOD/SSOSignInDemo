package com.example.ssosign_inpage

import android.content.Intent
import android.os.Bundle
import android.util.Log
import android.view.View
import android.widget.Toast
import androidx.appcompat.app.AppCompatActivity
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.lifecycle.lifecycleScope
import com.example.ssosign_inpage.databinding.ActivityMainBinding
import com.example.ssosign_inpage.utils.EmailValidator
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseUser
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.OAuthProvider
import kotlinx.coroutines.launch

class MainActivity : AppCompatActivity() {

    companion object {
        private const val TAG = "MainActivity"

        /**
         * Provider ID for enterprise SSO. Firebase supports SAML ("saml.xxx") and
         * OIDC ("oidc.xxx") providers through Google Cloud Identity Platform.
         * Replace with the provider ID you configure in Firebase Console ->
         * Authentication -> Sign-in method.
         */
        private const val SSO_PROVIDER_ID = "oidc.sso"
    }

    private lateinit var binding: ActivityMainBinding
    private val auth by lazy { FirebaseAuth.getInstance() }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        binding = ActivityMainBinding.inflate(layoutInflater)
        setContentView(binding.root)

        // Already signed in? Skip straight to the welcome screen.
        auth.currentUser?.let {
            navigateToWelcome(it)
            return
        }

        setupClickListeners()
    }

    private fun setupClickListeners() {
        binding.continueSsoButton.setOnClickListener { handleSsoLogin() }
        binding.continueGoogleButton.setOnClickListener { signInWithGoogle() }
        binding.continueMicrosoftButton.setOnClickListener {
            signInWithOAuthProvider("microsoft.com", null)
        }
    }

    // SSO

    private fun handleSsoLogin() {
        val email = binding.emailInput.text.toString().trim()

        when {
            email.isEmpty() -> {
                binding.emailInputLayout.error = getString(R.string.error_email_empty)
            }
            !EmailValidator.isValid(email) -> {
                binding.emailInputLayout.error = getString(R.string.error_email_invalid)
            }
            else -> {
                binding.emailInputLayout.error = null
                signInWithOAuthProvider(SSO_PROVIDER_ID, email)
            }
        }
    }

    //  Microsoft / SAML / OIDC

    private fun signInWithOAuthProvider(providerId: String, loginHint: String?) {
        setLoading(true)
        val provider = OAuthProvider.newBuilder(providerId).apply {
            if (loginHint != null) addCustomParameter("login_hint", loginHint)
        }.build()

        // Resume a flow that was in progress if the activity was recreated.
        val pending = auth.pendingAuthResult
        val task = pending ?: auth.startActivityForSignInWithProvider(this, provider)

        task
            .addOnSuccessListener { result -> onSignInSuccess(result.user) }
            .addOnFailureListener { e -> onSignInFailure(e) }
    }

    // Google

    private fun signInWithGoogle() {
        setLoading(true)

        val googleOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            // Generated by the google-services plugin from google-services.json
            .setServerClientId(getString(R.string.default_web_client_id))
            .build()

        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleOption)
            .build()

        lifecycleScope.launch {
            try {
                val result = CredentialManager.create(this@MainActivity)
                    .getCredential(this@MainActivity, request)
                val credential = result.credential

                if (credential is CustomCredential &&
                    credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL
                ) {
                    val googleCred = GoogleIdTokenCredential.createFrom(credential.data)
                    firebaseAuthWithGoogle(googleCred.idToken)
                } else {
                    setLoading(false)
                    Log.w(TAG, "Unexpected credential type: ${credential.type}")
                }
            } catch (e: GetCredentialCancellationException) {
                setLoading(false)
                Toast.makeText(this@MainActivity, R.string.msg_sign_in_cancelled, Toast.LENGTH_SHORT).show()
            } catch (e: GetCredentialException) {
                onSignInFailure(e)
            }
        }
    }

    private fun firebaseAuthWithGoogle(idToken: String) {
        val credential = GoogleAuthProvider.getCredential(idToken, null)
        auth.signInWithCredential(credential)
            .addOnSuccessListener { result -> onSignInSuccess(result.user) }
            .addOnFailureListener { e -> onSignInFailure(e) }
    }

    // Helpers

    private fun onSignInSuccess(user: FirebaseUser?) {
        setLoading(false)
        if (user != null) navigateToWelcome(user)
    }

    private fun onSignInFailure(e: Exception) {
        setLoading(false)
        Log.e(TAG, "Sign-in failed", e)
        Toast.makeText(
            this,
            getString(R.string.msg_sign_in_failed, e.localizedMessage ?: e.javaClass.simpleName),
            Toast.LENGTH_LONG
        ).show()
    }

    private fun setLoading(loading: Boolean) {
        binding.continueSsoButton.isEnabled = !loading
        binding.continueGoogleButton.isEnabled = !loading
        binding.continueMicrosoftButton.isEnabled = !loading
    }

    private fun navigateToWelcome(user: FirebaseUser) {
        val intent = Intent(this, WelcomeActivity::class.java).apply {
            putExtra(WelcomeActivity.EXTRA_EMAIL, user.email ?: user.displayName)
            // Don't allow back-navigating to the sign-in screen
            flags = Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TASK
        }
        startActivity(intent)
        finish()
    }
}
